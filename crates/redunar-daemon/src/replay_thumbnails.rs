//! Native thumbnail access stays bound to the configured owned replay store.
use crate::{RedunarService, ReplayBudget, ReplayClipStore, ReplayStorageAccessError};
use std::fs::Metadata;

impl RedunarService {
    fn thumbnail_store(&self) -> Result<ReplayClipStore, ReplayStorageAccessError> {
        let settings = self
            .load_game_catalog()
            .map_err(|e| ReplayStorageAccessError::catalog(&e))?
            .global_profile
            .replay;
        ReplayClipStore::open_existing(
            self.replay_save_directory()?,
            ReplayBudget::from_settings(settings),
        )
        .map_err(|e| ReplayStorageAccessError::inventory(&e))
    }
    /// Read regenerable bytes for an already opened clip's validated identity.
    /// # Errors
    /// Rejects unsafe storage and clips no longer in the live inventory.
    pub fn cached_replay_thumbnail(
        &self,
        name: &str,
        expected: &Metadata,
    ) -> Result<Option<Vec<u8>>, ReplayStorageAccessError> {
        self.thumbnail_store()?
            .cached_thumbnail(name, expected)
            .map_err(|e| ReplayStorageAccessError::inventory(&e))
    }
    /// Retain generated bytes only if this process owns writes and the clip is
    /// still present with the identity the decoder opened.
    /// # Errors
    /// Rejects secondary owners, stale clips, unsafe storage and cache failures.
    pub fn cache_replay_thumbnail(
        &self,
        name: &str,
        expected: &Metadata,
        bytes: &[u8],
    ) -> Result<(), ReplayStorageAccessError> {
        if self.read_only {
            return Err(ReplayStorageAccessError::inventory(
                &"Redunar storage is read-only",
            ));
        }
        self.thumbnail_store()?
            .cache_thumbnail(name, expected, bytes)
            .map_err(|e| ReplayStorageAccessError::inventory(&e))
    }
}
